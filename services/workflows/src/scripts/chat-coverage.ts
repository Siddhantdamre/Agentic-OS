/**
 * Generates docs/new-109-pg-plan/gap26sept/chat-coverage.md (ASK-G01): one row
 * per chat tool and one per dashboard tab action (mutating API route). Status
 * cells already in the file are kept, so flipping a row to 🟢 after a live
 * /ask-ai probe survives regeneration. New rows start 🔴.
 * Run: pnpm build && pnpm chat-coverage
 */
import { readdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { TOOLS } from '../tool-definitions.js';
import { resolveCallRisk } from '../tool-executor.js';

export const REPO_ROOT = join(__dirname, '../../../..');
export const COVERAGE_PATH = join(REPO_ROOT, 'docs/new-109-pg-plan/gap26sept/chat-coverage.md');
const API_DIR = join(REPO_ROOT, 'apps/dashboard/app/api');

// Not tab actions: inbound provider callbacks, sign-in, the chat itself, public widget, platform admin, infra.
const SKIP_ROUTE = /^\/api\/(webhooks|auth|ask-ai|widget|platform|stream|health|trueforge)(\/|$)/;
const METHOD_RE = /export\s+(?:async\s+function|const)\s+(POST|PUT|PATCH|DELETE)\b/g;

export interface TabAction {
  method: string;
  path: string;
}

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name === 'route.ts' ? [join(dir, e.name)] : [],
  );
}

export function scanTabActions(apiDir = API_DIR): TabAction[] {
  const out: TabAction[] = [];
  for (const file of walk(apiDir)) {
    const path = '/api/' + relative(apiDir, file).split(sep).slice(0, -1).join('/');
    if (SKIP_ROUTE.test(path)) continue;
    for (const m of readFileSync(file, 'utf8').matchAll(METHOD_RE)) out.push({ method: m[1], path });
  }
  return out.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}

/** Row key (first backticked cell) → status (last cell) from an existing file. */
export function parseStatuses(md: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const line of md.split('\n')) {
    const m = /^\| `([^`]+)` \|(?:.*\|)? ([^|]+) \|$/.exec(line);
    if (m) map.set(m[1], m[2].trim());
  }
  return map;
}

export function renderChatCoverage(actions: TabAction[], previous: Map<string, string>): string {
  const status = (key: string) => previous.get(key) ?? '🔴';
  const toolRows = [...TOOLS]
    .sort((a, b) => a.tool.localeCompare(b.tool) || a.name.localeCompare(b.name))
    .map((t) => {
      const r = resolveCallRisk(t.tool, t.action);
      const risk = r ? r.risk : 'unknown';
      const approval = r ? (r.confirm ? 'yes' : 'no') : '?';
      return `| \`${t.name}\` | ${t.tool}.${t.action} | ${risk} | ${approval} | ${status(t.name)} |`;
    });
  const actionRows = actions.map((a) => {
    const key = `${a.method} ${a.path}`;
    return `| \`${key}\` | ${status(key)} |`;
  });
  return [
    '# Chat coverage matrix (ASK-G01)',
    '',
    'Every chat tool and every tab action must be doable from Ask AI. Generated by',
    '`services/workflows/src/scripts/chat-coverage.ts` (`pnpm --filter @darex/workflows chat-coverage`);',
    '`chat-coverage.test.ts` fails CI when a tool or mutating route has no row.',
    '',
    'Status: 🔴 not proven from `/ask-ai` · 🟡 unit-tested path, no live proof · 🟢 proved live from `/ask-ai`.',
    'Edit only the status cell; regeneration keeps it.',
    '',
    `## Chat tools (${toolRows.length})`,
    '',
    '| Tool | Provider.action | Risk | Approval | Status |',
    '|---|---|---|---|---|',
    ...toolRows,
    '',
    `## Tab actions (${actionRows.length})`,
    '',
    'Mutating dashboard API routes a tab calls. Webhooks, auth, the chat itself, the public widget and platform admin are excluded.',
    '',
    '| Action | Status |',
    '|---|---|',
    ...actionRows,
    '',
  ].join('\n');
}

if (require.main === module) {
  const previous = existsSync(COVERAGE_PATH) ? parseStatuses(readFileSync(COVERAGE_PATH, 'utf8')) : new Map();
  writeFileSync(COVERAGE_PATH, renderChatCoverage(scanTabActions(), previous));
  console.log(`wrote ${relative(REPO_ROOT, COVERAGE_PATH)}`);
  process.exit(0);
}
